package com.atrum.chat

import android.os.SystemClock
import java.util.concurrent.ConcurrentHashMap

/**
 * Свежесть статусов присутствия: «в сети», «печатает», «записывает голосовое».
 *
 * ⚠️ ЗАЧЕМ ОТДЕЛЬНЫЙ ОБЪЕКТ (репорты: «статус в сети не точен от слова совсем, онлайн держится
 * мало», «статус печатает не отображается и не точен»). Раньше каждое место считало одинаково
 * наивно:
 *
 *     now - profile.onlineTs < ТАЙМАУТ
 *
 * где `now` — МОИ часы, а штамп снят часами СОБЕСЕДНИКА. Два независимых устройства, между ними
 * нет ни сервера, ни общего времени. Отсюда две поломки, обе наблюдаемые:
 *
 *  1. РАСХОЖДЕНИЕ ЧАСОВ. Телефон партнёра отстаёт на полминуты (сел без сети, сбился NTP,
 *     ручная установка времени) — и он офлайн НАВСЕГДА, сколько бы он ни слал heartbeat: его
 *     штамп всегда «старше» моего таймаута, а «печатает» не загорается ни разу. Спешит —
 *     наоборот, он «в сети» вечно и «печатает» не гаснет. Никакой таймаут это не лечит, потому
 *     что сравниваются величины из разных систем отсчёта.
 *  2. ЭХО ЧУЖОГО ПРОФИЛЯ. Мой слот profiles.txt везёт копии профилей остальных, снятые когда-то
 *     раньше (см. ProfileSync.pushPresence). Если при слиянии победит моя копия, я получу СВОЙ
 *     ЖЕ устаревший снимок его presence — при том что его свежий heartbeat лежит рядом в его
 *     собственном слоте.
 *
 * ЧТО ДЕЛАЕТСЯ ВМЕСТО ЭТОГО. Чужой штамп не сравнивается с моими часами вообще. Он используется
 * только как ПРИЗНАК ИЗМЕНЕНИЯ: сдвинулся вперёд — значит сигнал живой прямо сейчас, и я засекаю
 * этот момент по СВОИМ монотонным часам. Дальше статус держится, пока с засечённого момента не
 * истекло окно. Абсолютные значения чужих часов в решении не участвуют — расхождение перестаёт
 * что-либо значить.
 *
 * Штамп, который НЕ сдвинулся (в том числе ноль), решение не меняет: это ровно то, чем выглядит
 * устаревшее эхо. Если человек действительно ушёл или перестал печатать, его штамп перестанет
 * двигаться, и окно закроется само. Ошибка «пересидел» ограничена одним окном; ошибка «показал
 * офлайн живого» и «не показал печать» не возникает вовсе. Для статусов присутствия это верный
 * размен: ложное «не в сети» люди замечают и оно их раздражает, задержка на погасании — нет.
 *
 * ⏱ Часы — [SystemClock.elapsedRealtime]: монотонные, не прыгают от перевода времени и от
 * NTP-подстройки (на currentTimeMillis тот же баг воспроизвёлся бы уже на МОЁМ устройстве).
 */
object Presence {

    /**
     * Сколько держать «в сети» после последнего замеченного сдвига heartbeat.
     *
     * ⚠️ Было 12 с при периоде heartbeat 5 с — то есть достаточно ДВУХ подряд не доехавших
     * публикаций, чтобы человек «вышел». По Tor один read-modify-write профиля спокойно
     * занимает несколько секунд, а реле отвечают неравномерно, поэтому две потери подряд — это
     * будни, а не сбой. Отсюда и жалоба «онлайн держится мало». Тридцать секунд — запас в пять
     * heartbeat: столько подряд не теряется даже на плохом канале, а закрывший приложение
     * человек всё равно погаснет меньше чем за минуту.
     */
    const val ONLINE_WINDOW_MS = 30_000L

    /**
     * Окно для «печатает» и «записывает голосовое».
     *
     * ⚠️ Это ТОЛЬКО СТРАХОВКА, а не основной способ погасить надпись. Основной — правило
     * «пришёл свежий heartbeat, а штамп печати не вырос» в [signal]: оно срабатывает за один
     * обмен с реле после реальной остановки, поэтому окно можно держать заведомо большим и не
     * бояться, что надпись замигает между публикациями heartbeat (они идут раз в 5 с ± джиттер,
     * плюс задержка чтения — окно обязано это перекрывать с запасом).
     *
     * До окна дело доходит, лишь когда от человека вообще ничего не приходит, — а в этом случае
     * он и так вот-вот перестанет считаться «в сети».
     */
    const val TYPING_WINDOW_MS = 8_000L

    /**
     * Предельный возраст сигнала печати, измеренный ЧАСАМИ САМОГО ОТПРАВИТЕЛЯ.
     *
     * ⚠️ ЭТО ГЛАВНАЯ ГАРАНТИЯ ПРОТИВ ЗАЛИПАНИЯ (репорт: «статус печатает залипает»). Все
     * остальные правила опираются на то, ЧТО ИЗМЕНИЛОСЬ между двумя чтениями, — а такие правила
     * ломаются, стоит чтениям пойти неровно: пропал тик, слились два обновления в одно, пришло
     * эхо вместо оригинала. Здесь же сравниваются две величины, снятые ОДНИМ И ТЕМ ЖЕ телефоном
     * в один и тот же момент публикации: [Profile.onlineTs] — когда он выходил на связь,
     * [Profile.typingTs] — когда он последний раз нажал клавишу. Разница между ними не зависит
     * ни от моих часов, ни от расхождения устройств, ни от истории чтений, и врать не может:
     * если человек не касался клавиатуры пять секунд, он не печатает — точка.
     *
     * Работает это только потому, что typingTs привязан к нажатию, а не к моменту публикации
     * (см. ChatActivity.lastKeystrokeMs). Пять секунд — период heartbeat: пока пальцы двигаются,
     * очередная публикация застаёт нажатие свежим, и надпись держится непрерывно.
     */
    const val TYPING_MAX_AGE_MS = 5_000L

    /**
     * Больше записей и не нужно: следим только за теми, кто отрисован на экране (собеседник в
     * 1:1, участники открытой беседы). Ограничение — страховка от накопления по забытым чатам.
     */
    private const val MAX_TRACKED = 512

    /** Разделитель частей ключа. Не встречается ни в chatId, ни в userId, ни в виде kind. */
    private const val SEP = "@SEP@"

    /** Суффикс ключа для отметки «докуда я уже видел heartbeat» (см. heartbeatAdvanced). */
    private const val WATERMARK = "w"

    private const val KIND_ONLINE = "o"
    private const val KIND_TYPING = "t"
    private const val KIND_RECORDING = "r"

    private class Seen(@JvmField val remoteTs: Long, @JvmField val localMs: Long)

    private val seen = ConcurrentHashMap<String, Seen>()

    private fun key(kind: String, chatId: String, userId: String) =
        kind + SEP + chatId + SEP + userId

    /**
     * Общее правило для всех трёх статусов: сдвиг штампа = сигнал живой, иначе — держим, пока
     * не истекло [windowMs] с последнего сдвига.
     *
     * Вызывать можно сколь угодно часто — внутри только hash-lookup; presence-тикер зовёт это
     * раз в секунду на каждого участника.
     */
    private fun fresh(kind: String, chatId: String, userId: String, ts: Long, windowMs: Long): Boolean {
        val k = key(kind, chatId, userId)
        val nowLocal = SystemClock.elapsedRealtime()
        val prev = seen[k]

        // Штамп сдвинулся вперёд — доказательство живого сигнала ПРЯМО СЕЙЧАС. Единственный
        // момент, когда чужое время вообще участвует в решении, и участвует оно только
        // сравнением с самим собой, а не с моими часами.
        if (ts > 0L && (prev == null || ts > prev.remoteTs)) {
            if (prev == null && seen.size >= MAX_TRACKED) seen.clear()
            seen[k] = Seen(ts, nowLocal)
            return true
        }

        // Сдвига нет. Про этого человека я ещё вообще ничего не видел — значит, сигнала нет.
        val p = prev ?: return false

        // Держим, пока не истекло окно с последнего РЕАЛЬНОГО сдвига. Устаревшее эхо и нулевой
        // штамп сюда же и попадают — и, как задумано, ничего не решают.
        return nowLocal - p.localMs < windowMs
    }

    /** «В сети» ли участник по его последнему heartbeat [onlineTs] (сырое Profile.onlineTs). */
    fun isOnline(chatId: String, userId: String, onlineTs: Long): Boolean =
        fresh(KIND_ONLINE, chatId, userId, onlineTs, ONLINE_WINDOW_MS)

    /**
     * Пришёл ли вместе с этим чтением СВЕЖИЙ heartbeat участника — то есть можно ли доверять
     * нулю в соседнем поле как настоящей остановке, а не как отпечатку старого эха.
     *
     * Отдельная отметка на каждого потребителя ([kind]) намеренно: иначе результат зависел бы
     * от того, в каком порядке экран спросил про печать, запись и присутствие, — а такие
     * зависимости ломаются при первой же перестановке строк.
     */
    private fun heartbeatAdvanced(kind: String, chatId: String, userId: String, onlineTs: Long): Boolean {
        if (onlineTs <= 0L) return false
        val k = key(kind + WATERMARK, chatId, userId)
        val prev = seen[k]
        if (prev != null && onlineTs <= prev.remoteTs) return false
        if (prev == null && seen.size >= MAX_TRACKED) seen.clear()
        seen[k] = Seen(onlineTs, SystemClock.elapsedRealtime())
        return true
    }

    /**
     * Печатает ли участник ([Profile.typingTs]).
     *
     * [onlineTs] нужен как доказательство свежести: приложение при остановке набора шлёт явный
     * typingTs = 0 и надпись правильно гасить сразу, но отличить этот ноль от нуля в устаревшем
     * эхе можно только по одному признаку — пришёл ли он в одном чтении с продвинувшимся
     * heartbeat. Пришёл — гасим немедленно; не пришёл — гасим по окну.
     */
    fun isTyping(chatId: String, userId: String, typingTs: Long, onlineTs: Long): Boolean =
        signal(KIND_TYPING, chatId, userId, typingTs, onlineTs)

    /** Записывает ли голосовое ([Profile.recordingTs]). Та же логика, что у [isTyping]. */
    fun isRecording(chatId: String, userId: String, recordingTs: Long, onlineTs: Long): Boolean =
        signal(KIND_RECORDING, chatId, userId, recordingTs, onlineTs)

    private fun signal(kind: String, chatId: String, userId: String, ts: Long, onlineTs: Long): Boolean {
        val k = key(kind, chatId, userId)
        val nowLocal = SystemClock.elapsedRealtime()
        val prev = seen[k]

        // 0. ВОЗРАСТ СИГНАЛА ПО ЧАСАМ ОТПРАВИТЕЛЯ — жёсткий потолок, проверяется первым.
        //    Обе величины сняты одним телефоном в один момент публикации, поэтому их разность
        //    не зависит ни от моих часов, ни от того, как шли чтения. Просрочено — гасим и
        //    забываем наблюдение, чтобы залипшая отметка не удержала надпись по окну ниже.
        if (ts > 0L && onlineTs > 0L && onlineTs - ts > TYPING_MAX_AGE_MS) {
            seen.remove(k)
            return false
        }

        // 1. Штамп сдвинулся вперёд — человек нажал клавишу уже после того, что я видел.
        if (ts > 0L && (prev == null || ts > prev.remoteTs)) {
            if (prev == null && seen.size >= MAX_TRACKED) seen.clear()
            seen[k] = Seen(ts, nowLocal)
            return true
        }

        // 2. Штамп НЕ сдвинулся, а heartbeat — сдвинулся. Значит от человека пришли свежие
        //    данные, и печати в них нет: он на связи и молчит. Это и есть доказательство
        //    остановки — гасим сразу, не дожидаясь окна.
        //
        //    ⚠️ Именно это правило чинит репорт «держится долго после печати», а не таймаут.
        //    Явный стоп-сигнал (typingTs = 0) до сюда доехать не может: слоты сливаются
        //    максимумом, и ноль всегда проигрывает моей же старой копии его профиля с
        //    ненулевым штампом. Поэтому остановку опознаём не по значению, а по тому, что
        //    значение перестало расти, — а копия эха расти не умеет по определению.
        //
        //    Ложного погасания во время набора это не даёт: пока человек печатает, штамп
        //    привязан к последнему нажатию (см. ChatActivity.lastKeystrokeMs) и растёт с
        //    каждой публикацией. Если он не вырос, а публикация пришла — клавиш между ними
        //    действительно не было.
        if (heartbeatAdvanced(kind, chatId, userId, onlineTs)) {
            seen.remove(k)
            return false
        }

        // 3. Ни то ни другое: от человека вообще ничего нового не пришло. Держим по окну —
        //    это страховка на случай, когда он замолчал целиком (тогда он и офлайн).
        val p = prev ?: return false
        return nowLocal - p.localMs < TYPING_WINDOW_MS
    }

    /**
     * Забыть наблюдения по чату. Вызывается при выходе из чата: если вернуться туда через час,
     * «в сети» не должно достаться по наследству от прошлой сессии до первого чтения.
     */
    fun forgetChat(chatId: String) {
        val needle = SEP + chatId + SEP
        val it = seen.keys.iterator()
        while (it.hasNext()) if (it.next().contains(needle)) it.remove()
    }
}
