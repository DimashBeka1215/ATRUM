package com.atrum.chat.mods

/**
 * ─────────────────────────────────────────────────────────────────────────────
 * Контракт системы модов Atrum (Фаза 1: только интерфейсы + метаданные).
 * ─────────────────────────────────────────────────────────────────────────────
 *
 * Модель безопасности (ОБЯЗАТЕЛЬНА, см. CLAUDE.md §1):
 *  1. Грузятся ТОЛЬКО моды, подписанные publisher-ключом Atrum (Schnorr/Ed25519),
 *     с проверкой подписи и anti-rollback по версии — как у RelayListStore.
 *     Третьи лица моды ставить не могут: модель доверия остаётся целой.
 *  2. Мод исполняется в процессе приложения — настоящей изоляции на Android нет.
 *     Единственная граница — [ModHost]: мод получает ТОЛЬКО то, что хост явно отдаёт.
 *     Никакого доступа к CryptoHelper, ключам, паролям, сырому транспорту чата.
 *  3. Манифест фиксирован — мод не может добавить Android-разрешения.
 *  4. Kill-switch: подписанный список отозванных версий отключает плохой мод.
 *
 * На Фазе 1 код .dex НЕ загружается — только каталог, доверие и UI-каркас.
 * DexClassLoader появится в Фазе 2.
 */

/**
 * Контракт одного мода. Мод предоставляет публичный класс с этим интерфейсом и
 * конструктором без аргументов. Хост создаёт его рефлексией ПОСЛЕ проверки подписи
 * .dex и вызывает [onLoad] с ограниченным [ModHost].
 */
interface AtrumMod {

    /** Стабильный идентификатор мода (совпадает с id в каталоге). */
    val id: String

    /** Вызывается один раз при включении мода. Здесь мод регистрирует свои точки входа. */
    fun onLoad(host: ModHost)

    /** Вызывается при выключении/выгрузке мода — освободить ресурсы. */
    fun onUnload() {}
}

/**
 * Узкий API, который хост даёт моду. Растёт ОСОЗНАННО, по мере реальных модов.
 * Принцип: только безопасные тематические возможности; ничего про крипто/ключи/сеть чата.
 *
 * Фаза 1 — минимальная поверхность. Фаза 3 добавит (под конкретные моды):
 *   registerSlashCommand, registerMessageAction, registerThemePack, registerStickerSource …
 */
interface ModHost {

    /** versionCode приложения — для проверок совместимости из мода. */
    val appVersionCode: Int

    /** Запись в общий журнал (без секретов). */
    fun log(message: String)

    /** Короткое уведомление пользователю (Toast). */
    fun toast(message: String)

    /**
     * Добавить пункт в подраздел настроек «Моды → <этот мод>».
     * Самая безопасная первая возможность: мод получает свой экранчик, не лезет в чужое.
     */
    fun registerSettingsItem(title: String, summary: String, onClick: () -> Unit)
}

/** Состояние мода в каталоге — для экрана «Моды». */
enum class ModState {
    /** Есть в каталоге, не установлен. */
    AVAILABLE,
    /** Установлен и включён. */
    ENABLED,
    /** Установлен, но выключен. */
    DISABLED,
    /** Установлен, в каталоге доступна новая версия. */
    UPDATE_AVAILABLE,
    /** Версия каталога/мода несовместима с этой версией приложения. */
    INCOMPATIBLE
}

/**
 * Метаданные мода из подписанного каталога (то, что показывает экран «Моды»).
 * Поле [signature] — подпись publisher-ключом над каноничной строкой
 * "id|version|sha256(dex)"; проверяется перед загрузкой .dex (Фаза 2).
 */
data class ModInfo(
    val id: String,
    val name: String,
    val description: String,
    val version: Int,
    val versionName: String,
    val minAppVersion: Int,
    val dexUrl: String,
    val dexSha256: String,
    /** FQN класса мода (реализует AtrumMod). Входит в подпись. */
    val entryClass: String,
    val signature: String
)
