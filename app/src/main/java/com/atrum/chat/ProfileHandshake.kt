package com.atrum.chat

import android.util.Base64
import java.security.MessageDigest

/**
 * Рукопожатие профилей: подтверждение «я реально получил твой эфемерный ключ».
 *
 * ЗАЧЕМ (репорт: «собеседник видит моё сообщение, но его ответ ко мне не приходит»).
 * Сессионный ключ forward secrecy выводится по ECDH из ДВУХ эфемерных ключей — моего и
 * партнёрского. Раньше [CryptoHelper.encrypt] переключался на него, как только я получил
 * ключ партнёра, НЕ зная, получил ли партнёр мой. Если мой профиль до него не доехал (а
 * публикация через Tor требует кворума реле и падает заметно чаще чтения), он физически не
 * может вывести тот же ключ — и не расшифровывает НИ ОДНОГО моего сообщения. При этом я его
 * сообщения читаю прекрасно, он ведь ещё на парольном шифровании. Получается ровно та
 * односторонняя картина, которую видел пользователь: «мои доходят, его ответы — нет».
 *
 * РЕШЕНИЕ. Каждая сторона публикует в своём профиле [Profile.ephAck] — отпечаток эфемерного
 * ключа ПАРТНЁРА, который она реально держит. Увидев в профиле партнёра отпечаток СВОЕГО
 * текущего ключа, я получаю доказательство, что он способен вывести общий ключ, — и только
 * тогда включаю сессионное шифрование. До этого пишу парольным форматом, который партнёр
 * гарантированно прочитает.
 *
 * Важно: гейтится ТОЛЬКО шифрование. Расшифровка по-прежнему принимает всё, что может
 * (CryptoHelper перебирает всё кольцо сессионных ключей), иначе уже отправленные сообщения
 * стали бы нечитаемыми — прямое нарушение §17.
 */
object ProfileHandshake {

    /** Текущая версия протокола профиля. Партнёр с pv >= 1 умеет присылать [Profile.ephAck]. */
    const val PROTOCOL_VERSION = 1

    /**
     * Отпечаток эфемерного ключа для подтверждения.
     *
     * Привязан к chatId — иначе подтверждение, выданное в ОДНОМ чате, засчиталось бы в другом
     * (тот же собеседник, другой чат): чужой чат не должен уметь открывать forward secrecy
     * здесь. Это не секрет и не подпись: отпечаток открытого ключа, его назначение —
     * однозначно указать, КАКОЙ именно ключ получен, не раздувая профиль полной копией.
     *
     * null, если ключа нет (беседы эфемерными ключами не пользуются) — тогда и подтверждать
     * нечего.
     */
    fun ackFor(partnerEphPubB64: String?, chatId: String): String? {
        if (partnerEphPubB64.isNullOrBlank()) return null
        return try {
            val digest = MessageDigest.getInstance("SHA-256")
                .digest("$partnerEphPubB64|$chatId".toByteArray(Charsets.UTF_8))
            Base64.encodeToString(digest, Base64.NO_WRAP).take(ACK_LEN)
        } catch (_: Exception) {
            null
        }
    }

    /**
     * Подтвердил ли партнёр получение МОЕГО текущего эфемерного ключа.
     *
     * @param partner            профиль партнёра, прочитанный из канала
     * @param myEphPubB64        мой текущий эфемерный ключ
     * @param chatId             домен подтверждения
     * @param myPublishConfirmed подтвердило ли чтение канала, что мой профиль реально лежит
     *                           на реле (см. ChatActivity.confirmMyProfilePublished)
     *
     * Для СТАРОГО партнёра (pv отсутствует) подтверждения не будет никогда — он о нём не знает.
     * Ломать с ним forward secrecy нельзя (§17: старые чаты не должны терять функции), поэтому
     * опираемся на подтверждённую публикацию: если моё чтение канала видит мой собственный слот
     * на реле, партнёру физически есть что забрать. Это заметно строже прежнего «включаем
     * всегда», но мягче, чем полный отказ от FS со старыми версиями.
     */
    fun partnerHasMyKey(
        partner: Profile?,
        myEphPubB64: String?,
        chatId: String,
        myPublishConfirmed: Boolean
    ): Boolean {
        if (partner == null) return false
        if (myEphPubB64.isNullOrBlank()) return false
        if (partner.pv >= PROTOCOL_VERSION) {
            val expected = ackFor(myEphPubB64, chatId) ?: return false
            return partner.ephAck == expected
        }
        return myPublishConfirmed
    }

    /** Длина отпечатка. 16 символов base64 ≈ 96 бит — коллизия исключена, профиль не раздувается. */
    private const val ACK_LEN = 16
}
